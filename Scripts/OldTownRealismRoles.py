"""Surface-specific street roles; preserves the existing faded colour families."""
def role(path,label='',component='',box=None):
    n=path.rsplit('/',1)[-1].lower()
    if 'mainhome' in n:return None
    if box and box.get('role')=='floor':return 'Stone'
    if 'asphalt' in n:return 'Asphalt'
    if 'sidewalk' in n:return 'Concrete'
    if 'puddle' in n or 'wetpatch' in n:return 'Puddle'
    if 'roadmarking' in n:return 'Marking'
    if 'stain' in n:return 'Stain'
    if 'redbrick' in n:return 'RedBrick'
    if 'fadedbluewall' in n:return 'BluePlaster'
    if 'fadedgreenwall' in n:return 'GreenPlaster'
    if 'schoolwall' in n or 'interior' in n:return 'Plaster'
    if 'concrete' in n or 'floor' in n:return 'Concrete'
    if 'glass' in n:return 'Glass'
    if 'clothpiping' in n:return 'LinenSeam'
    if 'linen' in n or 'cloth' in n:return 'Linen'
    if 'ceramic' in n or 'enamel' in n:return 'Ceramic'
    if 'brass' in n:return 'Brass'
    if 'rubber' in n or 'blackwire' in n:return 'Rubber'
    if 'plastic' in n:return 'Plastic'
    if 'cardboard' in n:return 'Cardboard'
    if 'soil' in n:return 'Soil'
    if 'leaf' in n:return 'Leaf'
    if 'wood' in n:return 'Wood'
    if 'letters' in n:return 'Letters'
    if 'paper' in n:return 'Paper'
    if 'fadedblue' in n:return 'BluePaint'
    if 'fadedred' in n:return 'RedPaint'
    if 'fadedochre' in n:return 'OchrePaint'
    if 'greensign' in n:return 'GreenPaint'
    if 'greenmetal' in n or 'paintedmetal' in n:return 'PaintedMetal'
    if 'rust' in n:return 'Rust'
    if 'metal' in n:return 'DarkMetal'
    if 'dark' in n or 'shadow' in n:return 'DarkMetal'
    return None
